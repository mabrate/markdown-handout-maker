'use strict';
// Optional native UI check; install Playwright or set PLAYWRIGHT_MODULE.
const { _electron } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('assert/strict');
const fs = require('fs/promises');
const os = require('os');
const path = require('path');
const YAML = require('yaml');
(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'handout-document-settings-'));
  let application;
  try {
    const root = path.join(temporary, 'lessons'); await fs.mkdir(root);
    const body = '# Lesson skeleton\n\n## Explore\n\n## Explain\n';
    const fixture = '---\nlayout: letter # keep paper comment\ncustom-document: keep\n---\n\n' + body;
    const filePath = path.join(root, 'lesson.md'); await fs.writeFile(filePath, fixture);
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
    application = await _electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, '..'), '--no-sandbox', '--user-data-dir=' + path.join(temporary, 'profile')], env, timeout: 20000 });
    const page = await application.firstWindow(); page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForLoadState('load');
    const menu = command => application.evaluate(({ BrowserWindow }, command) => BrowserWindow.getAllWindows()[0].webContents.send('menu:command', { command }), command);
    await application.evaluate(({ dialog, BrowserWindow }, root) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [root] });
      BrowserWindow.getAllWindows()[0].webContents.send('menu:command', { command: 'open-folder' });
    }, root);
    await page.locator('#file-tree').getByRole('button', { name: 'lesson.md', exact: true }).click();
    const source = page.locator('#source'), trigger = page.getByRole('button', { name: 'Document settings', exact: true });
    const dialog = page.getByRole('dialog', { name: 'Document settings', exact: true });
    const apply = () => dialog.getByRole('button', { name: 'Apply', exact: true }).click();
    const add = async (key, value) => {
      await dialog.getByLabel('Add lesson property', { exact: true }).selectOption(key);
      await dialog.getByRole('button', { name: 'Add property', exact: true }).click();
      const row = dialog.locator(`[data-property="${key}"]`);
      await row.locator('textarea,input').fill(value); return row;
    };
    const custom = async (key, type, value) => {
      await dialog.getByLabel('Add lesson property', { exact: true }).selectOption('custom');
      await dialog.getByLabel('Custom property name', { exact: true }).fill(key);
      await dialog.getByLabel('Custom property type', { exact: true }).selectOption(type);
      await dialog.getByRole('button', { name: 'Add property', exact: true }).click();
      const row = dialog.locator(`[data-property="${key}"]`);
      if (type === 'boolean') await row.getByLabel(key, { exact: true }).selectOption(value);
      else await row.locator('textarea,input').fill(value);
      return row;
    };
    await trigger.click(); assert.equal(await dialog.locator('.lesson-property').count(), 0);
    assert.equal(await dialog.getByLabel('Add lesson property', { exact: true }).locator('option').count(), 10);
    await apply(); assert.equal(await source.inputValue(), fixture);
    assert.doesNotMatch(await page.locator('.document-tab.active').innerText(), /\*/);
    await trigger.click(); await add('title', 'Discard this');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click(); assert.equal(await source.inputValue(), fixture);
    // The file menu remains useful when the editor panel is collapsed.
    await menu('document-settings'); await dialog.waitFor();
    await dialog.getByLabel('Page layout', { exact: true }).selectOption('a4');
    await add('title', 'Food webs planning'); await add('audience', 'Grade 7 science');
    await add('assignment', 'Build a food web.\nExplain what changes when a species disappears.');
    await add('learning-goals', 'Describe relationships\nPredict effects');
    await page.screenshot({ path: '/tmp/handout-document-settings.png' });
    await add('duration-minutes', '25');
    await custom('materials', 'list', 'Cards\nString'); await custom('outdoors', 'boolean', 'false');
    await dialog.getByLabel('Add lesson property', { exact: true }).selectOption('custom');
    await dialog.getByLabel('Custom property name', { exact: true }).fill('materials');
    await dialog.getByRole('button', { name: 'Add property', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: /already exists/ }).waitFor(); assert.equal(await source.inputValue(), fixture);
    await dialog.getByLabel('Custom property name', { exact: true }).fill('../escape');
    await dialog.getByRole('button', { name: 'Add property', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: /starting with a letter/ }).waitFor();
    await custom('grouping', 'yaml', 'size: [broken');
    await apply(); await dialog.getByRole('alert').filter({ hasText: /flow sequence|flow collection/i }).waitFor(); assert.equal(await source.inputValue(), fixture);
    await dialog.locator('[data-property="grouping"] textarea').fill('size: 3\nroles: [reader, recorder]');
    await source.evaluate(element => { const at = element.value.indexOf('Explore'); element.setSelectionRange(at, at + 7); });
    await apply(); await dialog.waitFor({ state: 'detached' });
    const result = await source.inputValue(), meta = YAML.parse(result.split('---')[1]);
    assert.equal(meta.layout, 'a4'); assert.equal(meta['custom-document'], 'keep'); assert.ok(result.includes('# keep paper comment'));
    assert.deepEqual(meta['lesson-info'], { title: 'Food webs planning', audience: 'Grade 7 science', assignment: 'Build a food web.\nExplain what changes when a species disappears.', 'learning-goals': ['Describe relationships', 'Predict effects'], 'duration-minutes': 25, materials: ['Cards', 'String'], outdoors: false, grouping: { size: 3, roles: ['reader', 'recorder'] } });
    assert.ok(result.endsWith('\n\n' + body));
    assert.equal(await source.evaluate(element => element.value.slice(element.selectionStart, element.selectionEnd)), 'Explore');
    assert.equal(await page.locator('#layout-select').inputValue(), 'a4');
    assert.match(await page.locator('.document-tab.active').innerText(), /\*/);
    assert.ok(!(await page.locator('#preview').innerText()).includes('Food webs planning'));
    await source.press('Control+z'); assert.equal(await source.inputValue(), fixture);
    await page.waitForFunction(() => document.querySelector('#layout-select').value === 'letter');
    await source.press('Control+Shift+z'); assert.equal(await source.inputValue(), result);
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('menu:command', { command: 'set-layout', payload: 'letter-landscape' }));
    await page.waitForFunction(() => document.querySelector('#layout-select').value === 'letter-landscape');
    assert.equal(YAML.parse((await source.inputValue()).split('---')[1]).layout, 'letter-landscape');
    await source.press('Control+z'); assert.equal(await source.inputValue(), result);
    await page.waitForFunction(() => document.querySelector('#layout-select').value === 'a4');
    await menu('save'); await page.waitForFunction(() => !document.querySelector('.document-tab.active').textContent.includes('*'));
    assert.equal(await fs.readFile(filePath, 'utf8'), result);
    await trigger.click(); assert.equal(await dialog.getByLabel('Title', { exact: true }).inputValue(), 'Food webs planning');
    assert.equal(await dialog.getByLabel('Page layout', { exact: true }).locator('option[value=""]').innerText(), 'Use app layout (Letter)');
    await dialog.getByLabel('Page layout', { exact: true }).selectOption(''); await apply();
    assert.equal(YAML.parse((await source.inputValue()).split('---')[1]).layout, undefined);
    assert.equal(await page.locator('#layout-select').inputValue(), 'letter');
    await source.press('Control+z'); assert.equal(await source.inputValue(), result);
    await trigger.click();
    await dialog.getByRole('button', { name: 'Remove Audience', exact: true }).click(); await apply();
    assert.ok(!YAML.parse((await source.inputValue()).split('---')[1])['lesson-info'].audience);
    // Source edits become the next dialog's values, including nested custom metadata.
    await source.fill('---\nlayout: "half-landscape"\nlesson-info:\n  title: Manual title\n  rubric: { levels: [one, two] }\n---\n' + body);
    await trigger.click(); assert.equal(await dialog.getByLabel('Title', { exact: true }).inputValue(), 'Manual title');
    assert.equal(await dialog.getByLabel('rubric value type', { exact: true }).inputValue(), 'yaml');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#layout-select').value === 'half-landscape');
    const invalid = '---\nlesson-info:\n  title: [broken\n---\n' + body;
    await source.fill(invalid); await trigger.click(); assert.equal(await dialog.getByRole('button', { name: 'Apply', exact: true }).isDisabled(), true);
    assert.ok((await dialog.getByRole('alert').innerText()).length > 0);
    await dialog.getByRole('button', { name: 'Show YAML', exact: true }).click(); assert.equal(await source.inputValue(), invalid);
    assert.ok(await source.evaluate(element => element.selectionEnd > element.selectionStart));
    // A menu or external source replacement must never be overwritten by a stale form.
    await source.fill(fixture); await trigger.click(); await add('title', 'Stale draft');
    await source.evaluate(element => { element.value = '# Changed elsewhere'; element.dispatchEvent(new Event('input', { bubbles: true })); });
    await apply(); await dialog.getByRole('alert').filter({ hasText: /document changed/ }).waitFor(); assert.equal(await source.inputValue(), '# Changed elsewhere');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await source.fill('---\ntype: slides\nlesson-info:\n  audience: Grade 7\n---\n# First slide\n\n---\n# Second slide');
    await trigger.click(); assert.equal(await dialog.getByLabel('Page layout', { exact: true }).count(), 0);
    await dialog.getByLabel('Slide theme', { exact: true }).selectOption('dark'); await dialog.getByLabel('Slide aspect ratio', { exact: true }).selectOption('4:3');
    await page.emulateMedia({ media: 'print' }); assert.equal(await page.locator('.document-settings-dialog').isVisible(), false); await page.emulateMedia({ media: 'screen' });
    await apply();
    const deck = require('../renderer/slides').parse(await source.inputValue());
    assert.equal(deck.settings.theme, 'dark'); assert.equal(deck.settings.aspect, '4:3'); assert.equal(deck.slides.length, 2);
    assert.equal(YAML.parse((await source.inputValue()).split('---')[1])['lesson-info'].audience, 'Grade 7');
    await menu('save'); await page.waitForFunction(() => !document.querySelector('.document-tab.active').textContent.includes('*'));
    await page.getByRole('button', { name: 'Close lesson.md', exact: true }).click();
    assert.equal(await trigger.isDisabled(), true); await menu('document-settings'); assert.equal(await dialog.count(), 0);
    assert.deepEqual(errors, []);
    console.log('Native document settings: optional/custom lesson fields, typed YAML, validation, Cancel, Undo/Redo, layout, source selection, saving, slides, and print isolation passed');
  } finally {
    if (application) await application.evaluate(({ app }) => app.exit(0)).catch(() => {});
    await fs.rm(temporary, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
